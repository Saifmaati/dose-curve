/* MaatiRx: a practice worksheet's view and print (2.15)
   A sheet of problems from the chosen topic (PK.makeWorksheet): on screen with an answers toggle, printed black on white
   with the answer key on its own page; its link (#ws=topic.count.seed) rebuilds it. Loaded with the first worksheet;
   the page passes what it needs through ctx. Educational model, not for clinical dosing. */
(function(root){
  "use strict";
  root.DCWorksheet=function(ctx){
    const {$, PK, esc, copyHash, clearTaskHash, reduceMotion}=ctx;
    let ws=null;
    const topicTitle=id=> id ? PK.PRACTICE_TOPICS.find(t=>t.id===id).title : "All topics";
    const wsLinkHash=()=> PK.encodeTaskLink({type:"worksheet", topic:ws.topic, count:ws.count, seed:ws.seed, v:ws.v});
    const ansText=pr=> `${pr.ans.toFixed(pr.dp)}${pr.unit && pr.unit!=="(fraction)" ? " "+pr.unit : ""}`;
    function showWorksheet(w, shared){
      if(!shared) clearTaskHash();
      ws=w;
      $("wsTitle").textContent=`Worksheet: ${topicTitle(w.topic)}, ${w.count} problems`;
      $("wsCode").textContent=`code ${wsLinkHash().slice(3)}`;
      $("wsShared").hidden=!shared;
      $("wsAnswers").setAttribute("aria-pressed","false"); $("wsAnswers").textContent="Show answers";
      $("wsList").innerHTML=w.problems.map(pr=>`<li><span class="ws-type">${pr.type}</span><div>${pr.q}</div>`+
        `<div class="ws-a" hidden>Answer: <b>${ansText(pr)}</b>${pr.sol.join("")}</div></li>`).join("");
      $("wsView").hidden=false;
      $("wsTitle").focus({preventScroll:true});
      $("wsView").scrollIntoView({behavior:reduceMotion()?"auto":"smooth", block:"start"});
    }
    $("wsAnswers").addEventListener("click",()=>{
      const on=$("wsAnswers").getAttribute("aria-pressed")!=="true";
      $("wsAnswers").setAttribute("aria-pressed", on); $("wsAnswers").textContent=on ? "Hide answers" : "Show answers";
      $("wsList").querySelectorAll(".ws-a").forEach(a=> a.hidden=!on);
    });
    $("wsLink").addEventListener("click",()=>{ if(ws) copyHash(wsLinkHash()); });
    $("wsClose").addEventListener("click",()=>{ ws=null; $("wsView").hidden=true; clearTaskHash(); $("wsMake").focus(); });
    $("wsPrintBtn").addEventListener("click",()=>{
      if(!ws) return;
      const url=location.href.split("#")[0]+"#"+wsLinkHash();
      $("wsPrint").innerHTML=`<h1>MaatiRx practice worksheet</h1>`+
        `<p class="wp-meta">${esc(topicTitle(ws.topic))}, ${ws.count} problems, code ${esc(wsLinkHash().slice(3))}</p>`+
        `<p class="wp-meta">Open it online: ${esc(url)}</p>`+
        `<ol>${ws.problems.map(pr=>`<li><span class="wp-type">${pr.type}</span><div>${pr.q}</div><div class="wp-ans">Answer: ______________ ${pr.unit}</div></li>`).join("")}</ol>`+
        `<section class="wp-key"><h2>Answer key</h2><ol>${ws.problems.map(pr=>`<li><b>${ansText(pr)}</b> (${pr.type})<div>${pr.sol.join("")}</div></li>`).join("")}</ol></section>`+
        `<footer>Generated by MaatiRx, an educational pharmacokinetic simulation. Not for dosing real patients.</footer>`;
      document.body.classList.add("ws-printing");
      window.print();
    });
    window.addEventListener("afterprint",()=> document.body.classList.remove("ws-printing"));
    return {show:showWorksheet};
  };
})(typeof self!=="undefined" ? self : this);
